export const DEFAULT_EXCHANGE_RATE = 5.80; // USD to BRL rate

export function toBrl(usdCredits: number, rate = DEFAULT_EXCHANGE_RATE): number {
  return Number((usdCredits * rate).toFixed(2));
}

export function formatPriceBrl(usdCredits: number, rate = DEFAULT_EXCHANGE_RATE): string {
  const brl = toBrl(usdCredits, rate);
  return `R$ ${brl.toLocaleString("pt-BR", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

export function formatRunwareCredits(usdCredits: number): string {
  // Runware credit points (e.g. 0.03 USD -> ≈ 1.4 or 3 credits)
  return (usdCredits * 50).toLocaleString("pt-BR", { minimumFractionDigits: 1, maximumFractionDigits: 1 });
}

